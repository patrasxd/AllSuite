export function getDraftButtonTooltip(locale: Locale, label: string): string | undefined {
  return normalizeButtonTooltip(resolveDraftButtonTooltip(locale, label))
}

function resolveDraftButtonTooltip(locale: Locale, label: string): string | undefined {
  const normalized = label
    .replace(/\s*\([^)]*\)/g, '')
    .replace(/\s+/g, ' ')
    .trim()
  const direct = descriptions[locale][label] ?? descriptions[locale][normalized]
  if (direct) return direct

  if (locale === 'en') {
    if (/^edit rich headers and footers/i.test(label)) return 'Edit this page header or footer.'
    if (/^edit\s+.*\bheader\b/i.test(label)) return 'Edit this page header.'
    if (/^edit\s+.*\bfooter\b/i.test(label)) return 'Edit this page footer.'
    if (/^blank document\b/i.test(label)) return 'Start with a clean document page.'
    if (/^collapse\b/i.test(label)) return 'Hide this document section.'
    if (/^expand\b/i.test(label)) return 'Show this document section.'
    if (/^move up\b/i.test(label)) return 'Move this section earlier.'
    if (/^move down\b/i.test(label)) return 'Move this section later.'
    if (/^\d+\s*[×x]\s*\d+$/.test(label)) return `Insert a ${label} table.`
    if (/^previous toolbar page/i.test(label)) return 'Show the previous tool group.'
    if (/^next toolbar page/i.test(label)) return 'Show the next tool group.'
    if (/^insert\s+\S+\s*$/i.test(label)) return 'Insert the selected symbol.'
    if (/^edit\b|^resize\b/i.test(label)) return 'Edit the selected document item.'
    if (/^insert\b/i.test(label)) return 'Insert the selected item.'
    if (label.length > 80) return 'Use this starter layout to create a document.'
  } else {
    if (/^edytuj nagłówki i stopki/i.test(label)) return 'Edytuj nagłówek lub stopkę strony.'
    if (/^zwiń\b/i.test(label)) return 'Ukryj tę sekcję dokumentu.'
    if (/^rozwiń\b/i.test(label)) return 'Pokaż tę sekcję dokumentu.'
    if (/^przenieś wyżej\b/i.test(label)) return 'Przenieś tę sekcję wcześniej.'
    if (/^przenieś niżej\b/i.test(label)) return 'Przenieś tę sekcję później.'
    if (/^\d+\s*[×x]\s*\d+$/.test(label)) return `Wstaw tabelę ${label}.`
    if (/^wstaw\s+\S+\s*$/i.test(label)) return 'Wstaw wybrany symbol.'
    if (/^(edytuj|zmień rozmiar)\b/i.test(label)) return 'Edytuj wybrany element dokumentu.'
    if (/^wstaw\b/i.test(label)) return 'Wstaw wybrany element.'
    if (label.length > 80) return 'Użyj tego układu, aby utworzyć dokument.'
  }
  return undefined
}

