import { expect, test } from '@playwright/test'
import type { Editor } from '@tiptap/core'

test('one Painter button applies once or repeatedly with a native double-click', async ({ page }) => {
  await page.goto('./apps/draft')
  const editor = page.getByRole('textbox', { name: 'Document editor', exact: true })
  await editor.fill('Source First Second Third')
  const select = (from: number, to: number) =>
    editor.evaluate(
      (element, range) => {
        ;(element as HTMLElement & { editor: Editor }).editor.commands.setTextSelection(range)
      },
      { from, to },
    )
  const painter = page.getByRole('button', { name: 'Format painter', exact: true })
  await expect(painter).toHaveCount(1)
  await select(1, 7)
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  await painter.click()
  await select(8, 13)
  await expect(editor.locator('strong')).toHaveText(['Source', 'First'])
  await expect(painter).toHaveAttribute('aria-pressed', 'false')
  await select(1, 7)
  await painter.dblclick()
  await select(14, 20)
  await expect(painter).toHaveAttribute('aria-pressed', 'true')
  await select(21, 26)
  await expect(editor.locator('strong')).toHaveText(['Source', 'First', 'Second', 'Third'])
  await expect(painter).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await expect(painter).toHaveAttribute('aria-pressed', 'false')
})

test('Home disclosures format the real selection and styles retain editor history', async ({ page }) => {
  await page.goto('./apps/draft')
  const editor = page.getByRole('textbox', { name: 'Document editor', exact: true })
  await editor.fill('A real document selection')
  await editor.press('Control+a')
  const home = page.getByRole('toolbar', { name: 'Home', exact: true })
  for (const name of ['Clipboard', 'Font', 'Paragraph', 'Styles', 'Editing'])
    await expect(home.getByRole('group', { name, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'More formatting', exact: true }).click()
  await page.getByRole('button', { name: 'Strikethrough', exact: true }).click()
  await expect(editor.locator('s')).toHaveText('A real document selection')
  await page.getByRole('button', { name: 'Text style', exact: true }).click()
  await page.getByRole('button', { name: 'Heading 2', exact: true }).click()
  await expect(editor.locator('h2')).toHaveText('A real document selection')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(editor.locator('h2')).toHaveCount(0)
  await expect(editor.locator('s')).toHaveText('A real document selection')
  await page.getByRole('button', { name: 'File', exact: true }).click()
  await expect(page.getByRole('button', { name: 'New', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'File', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Text color', exact: true }).click()
  await expect(page.locator('input[type="color"][aria-label="Text color"]')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Text color', exact: true })).toBeFocused()
  await expect(page.locator('.allsuite-ribbon-menu__items')).toHaveCount(0)
})

test('mobile quick formatting, More, Back and shortened viewport keep the editor usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./apps/draft')
  const editor = page.getByRole('textbox', { name: 'Document editor', exact: true })
  await expect(page.locator('.draft-page')).toHaveClass(/draft-page--web/)
  await editor.fill('Mobile selection stays editable')
  await editor.press('Control+a')
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  await expect(editor.locator('strong')).toHaveText('Mobile selection stays editable')
  const more = page.getByRole('button', { name: 'More', exact: true })
  await more.click()
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Italic', exact: true }).click()
  await expect(editor.locator('em')).toHaveText('Mobile selection stays editable')
  await page.setViewportSize({ width: 390, height: 480 })
  const find = page.getByRole('button', { name: 'Find', exact: true })
  await find.scrollIntoViewIfNeeded()
  await find.click()
  await expect(page.getByRole('textbox', { name: 'Find', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(more).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(() => page.evaluate(() => Boolean(window.history.state?.draftRibbonMore))).toBe(false)
  await more.click()
  await expect.poll(() => page.evaluate(() => Boolean(window.history.state?.draftRibbonMore))).toBe(true)
  await page.goBack()
  await expect(more).toHaveAttribute('aria-expanded', 'false')
  await expect(page).toHaveURL(/\/apps\/draft$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(editor).toContainText('Mobile selection stays editable')
  await editor.focus()
  await editor.press('Control+End')
  await expect.poll(() => page.evaluate(() => window.getSelection()?.isCollapsed)).toBe(true)
  await expect
    .poll(() =>
      editor.evaluate((element) => (element as HTMLElement & { editor: Editor }).editor.state.selection.empty),
    )
    .toBe(true)
  await editor.pressSequentially('!')
  await expect(editor).toContainText('editable!')
  expect((await page.locator('.draft-document-area').boundingBox())!.height).toBeGreaterThan(80)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
