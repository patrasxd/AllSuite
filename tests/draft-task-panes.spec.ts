import { expect, test, type Page } from '@playwright/test'
import type { Editor } from '@tiptap/core'

const evidence = 'docs/verification/task-panes/'
const editorOf = (page: Page) => page.getByRole('textbox', { name: 'Document editor', exact: true })
const paneOf = (page: Page) => page.locator('.allsuite-task-pane-host:not([hidden])')
async function select(page: Page, from: number, to = from) {
  await editorOf(page).evaluate(
    (element, range) => {
      ;(element as HTMLElement & { editor: Editor }).editor.commands.setTextSelection(range)
    },
    { from, to },
  )
}
async function openReview(page: Page) {
  await page.getByRole('tab', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: /^Review changes(?: \(\d+\))?$/ }).click()
}

test('one task pane switches both directions, toggles, restores workspace and preserves unsent comments/replies', async ({
  page,
}) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('./apps/draft')
  await editorOf(page).fill('Project review\nA document with comments and tracked changes.\nNext steps')
  const closedWidth = await page.locator('.draft-document-area').evaluate((element) => element.clientWidth)
  await page.screenshot({ path: evidence + 'after-closed.png' })
  await select(page, 1, 8)
  await openReview(page)
  await page.getByRole('button', { name: /^Comments(?: \(\d+\))?$/ }).click()
  await expect(page.locator('.all-side-panel:visible')).toHaveCount(1)
  await expect(page.getByRole('complementary', { name: /^Comments(?: \(\d+\))?$/ })).toBeVisible()
  await expect(page.getByLabel('New comment', { exact: true })).toHaveCount(0)
  await paneOf(page).locator('.draft-pane-settings summary:visible').click()
  await page.getByLabel('Your name for this session').fill('Ada')
  await paneOf(page).getByRole('button', { name: 'New comment', exact: true }).click()
  await page.getByLabel('New comment', { exact: true }).fill('Check the project scope.')
  await paneOf(page).getByRole('button', { name: 'Add comment', exact: true }).click()
  await expect(paneOf(page).locator('.draft-comment-thread')).toHaveCount(1)
  await expect(page.getByLabel('New comment', { exact: true })).toHaveCount(0)
  await paneOf(page).getByRole('button', { name: 'Reply', exact: true }).click()
  await page.getByLabel('Reply to Ada').fill('Unsent reply stays here')
  await select(page, 1, 8)
  await paneOf(page).getByRole('button', { name: 'New comment', exact: true }).click()
  await page.getByLabel('New comment', { exact: true }).fill('Unsent comment stays here')
  await page.screenshot({ path: evidence + 'after-comments.png' })
  const openWidth = await page.locator('.draft-document-area').evaluate((element) => element.clientWidth)
  expect(closedWidth - openWidth).toBe(340)
  await page.getByRole('button', { name: /^Review changes(?: \(\d+\))?$/ }).click()
  await expect(page.getByRole('complementary', { name: /^Review changes(?: \(\d+\))?$/ })).toBeVisible()
  await expect(page.locator('.all-side-panel:visible')).toHaveCount(1)
  await page.screenshot({ path: evidence + 'after-switch-review.png' })
  expect(
    await editorOf(page).evaluate((element) => {
      const e = (element as HTMLElement & { editor: Editor }).editor
      return e.state.doc.textBetween(e.state.selection.from, e.state.selection.to)
    }),
  ).toBe('Project')
  await page.getByRole('button', { name: /^Comments(?: \(\d+\))?$/ }).click()
  await expect(page.locator('.all-side-panel:visible')).toHaveCount(1)
  await expect(page.getByLabel('New comment', { exact: true })).toHaveValue('Unsent comment stays here')
  await expect(page.getByLabel('Reply to Ada')).toHaveValue('Unsent reply stays here')
  await page.screenshot({ path: evidence + 'after-switch-comments.png' })
  await paneOf(page).locator('.draft-comment-anchor-link').click()
  await expect
    .poll(() =>
      editorOf(page).evaluate((element) => {
        const e = (element as HTMLElement & { editor: Editor }).editor
        return e.state.doc.textBetween(e.state.selection.from, e.state.selection.to)
      }),
    )
    .toBe('Project')
  await page.getByLabel('Reply to Ada').fill('Scope confirmed.')
  await paneOf(page).locator('.draft-comment-reply-form').getByRole('button', { name: 'Reply', exact: true }).click()
  await expect(paneOf(page).locator('.draft-comment-reply')).toContainText('Scope confirmed.')
  await paneOf(page).getByRole('button', { name: 'Resolve', exact: true }).click()
  await expect(paneOf(page).locator('.draft-comment-thread')).toHaveClass(/is-resolved/)
  await page.keyboard.press('Escape')
  await expect(paneOf(page)).toHaveCount(0)
  await expect(editorOf(page)).toBeFocused()
  expect(await page.locator('.draft-document-area').evaluate((element) => element.clientWidth)).toBe(closedWidth)
  await page.getByRole('button', { name: /^Comments(?: \(\d+\))?$/ }).click()
  await expect(page.getByLabel('New comment', { exact: true })).toHaveValue('Unsent comment stays here')
  await page.getByRole('button', { name: /^Comments(?: \(\d+\))?$/ }).click()
  await expect(paneOf(page)).toHaveCount(0)
})

test('Navigation shares search/replace/headings, focuses shortcuts and keeps document history', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('./apps/draft')
  await editorOf(page).fill('Project review')
  await editorOf(page).press('Control+Alt+1')
  await editorOf(page).press('End')
  await editorOf(page).press('Enter')
  await editorOf(page).pressSequentially('Review the project. Review the scope.')
  await openReview(page)
  await page.keyboard.press('Control+f')
  await expect(page.getByRole('textbox', { name: 'Find', exact: true })).toBeFocused()
  await page.getByRole('textbox', { name: 'Find', exact: true }).fill('Review')
  await expect(page.locator('.draft-search-results li')).toHaveCount(3)
  await page.screenshot({ path: evidence + 'after-navigation-results.png' })
  await page.locator('.draft-search-results li').nth(1).getByRole('button').click()
  await expect(editorOf(page)).toBeFocused()
  await page.keyboard.press('Control+h')
  await expect(page.locator('.all-side-panel:visible')).toHaveCount(1)
  await expect(page.getByRole('textbox', { name: 'Find', exact: true })).toHaveValue('Review')
  await page.getByRole('textbox', { name: 'Replace with', exact: true }).fill('Check')
  await page.screenshot({ path: evidence + 'after-find-replace.png' })
  await paneOf(page).getByRole('button', { name: 'Replace all', exact: true }).click()
  await expect(editorOf(page)).toContainText('Check the project. Check the scope.')
  await paneOf(page).getByRole('button', { name: 'Headings', exact: true }).click()
  await expect(page.locator('.draft-search-match')).toHaveCount(0)
  await expect(paneOf(page).getByRole('treeitem')).toHaveCount(1)
  await page.screenshot({ path: evidence + 'after-headings.png' })
  await paneOf(page).getByRole('button', { name: 'Project Check', exact: true }).click()
  await expect(editorOf(page)).toBeFocused()
  await page.keyboard.press('Escape')
  await editorOf(page).press('Control+z')
  await expect(editorOf(page)).toContainText('Review the project. Review the scope.')
})

test('tracking survives closing and revisions retain accept/reject and undo semantics', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('./apps/draft')
  await editorOf(page).fill('Review this document.')
  await openReview(page)
  await paneOf(page).locator('.draft-pane-settings summary:visible').click()
  await paneOf(page).getByLabel('Author name').fill('Ada')
  await expect(paneOf(page).getByRole('switch', { name: 'Track changes', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Track changes', exact: true }).click()
  await page.keyboard.press('Escape')
  await editorOf(page).press('Control+End')
  await editorOf(page).pressSequentially(' Added for review.')
  await page.getByRole('button', { name: /^Review changes(?: \(\d+\))?$/ }).click()
  await expect(paneOf(page).getByRole('article')).toHaveCount(1)
  await expect(paneOf(page).getByRole('article')).toContainText('Ada')
  await page.screenshot({ path: evidence + 'after-review.png' })
  await paneOf(page).locator('.draft-suggestion-jump').click()
  await expect(editorOf(page)).toBeFocused()
  await paneOf(page).getByRole('button', { name: 'Reject', exact: true }).click()
  await expect(editorOf(page)).not.toContainText('Added for review.')
  await editorOf(page).press('Control+z')
  await expect(paneOf(page).getByRole('article')).toHaveCount(1)
  await paneOf(page).getByRole('button', { name: 'Accept all', exact: true }).click()
  await expect(paneOf(page).getByRole('article')).toHaveCount(0)
  await expect(editorOf(page)).toContainText('Added for review.')
  await editorOf(page).press('Control+End')
  await editorOf(page).pressSequentially(' Another change.')
  await paneOf(page).getByRole('button', { name: 'Reject all', exact: true }).click()
  await expect(editorOf(page)).not.toContainText('Another change.')
})

