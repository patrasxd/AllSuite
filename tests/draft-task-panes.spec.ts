test('an open pane follows viewport changes without triggering dirty-document navigation', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('./apps/draft')
  await editorOf(page).fill('Keep this unsaved document.')
  await page.keyboard.press('Control+f')
  await expect(paneOf(page)).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => Boolean(history.state?.allsuiteTaskPane))).toBe(true)
  await page.goBack()
  await expect(paneOf(page)).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(editorOf(page)).toBeFocused()
  await page.keyboard.press('Control+h')
  await expect(paneOf(page)).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect.poll(() => page.evaluate(() => Boolean(history.state?.allsuiteTaskPane))).toBe(false)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(paneOf(page)).toHaveCount(0)
  await expect(editorOf(page)).toContainText('Keep this unsaved document.')
})
